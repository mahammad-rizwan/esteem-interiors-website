// Exports the curated photos (WebP, 3 sizes) and videos (silent H.264 MP4 + poster)
// from the client's Resources folder into public/media, and writes src/data/media.generated.js.
// Usage: FFMPEG=<path to ffmpeg> node scripts/build-media.mjs
import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import sharp from 'sharp';

const FFMPEG = process.env.FFMPEG || 'ffmpeg';
const OUT = path.resolve('public/media');
const photoIndex = JSON.parse(fs.readFileSync('scripts/media/photo-index.json', 'utf8'));
const videoIndex = JSON.parse(fs.readFileSync('scripts/media/video-index.json', 'utf8'));

// Hand-picked from the contact sheets (numbers refer to the index files).
export const PICKS = {
  'pizza-hsr': {
    photos: [17, 6, 21, 31, 36, 46, 49, 51, 54, 56, 60, 61, 64, 66, 69, 74, 79, 84, 103, 107],
    videos: [26, 3, 4, 7, 10, 14, 17, 21, 25, 43],
  },
  'pizza-koramangala': {
    photos: [74, 2, 4, 9, 11, 17, 21, 23, 34, 42, 45, 50, 58, 60, 66, 79, 85, 88, 93, 97],
    videos: [1, 3, 7, 11, 17, 19, 21, 29, 33, 39],
  },
  'hyundai-rajajinagar': {
    photos: [1, 2, 3, 6, 9, 10, 14, 19, 20, 23, 28, 30, 35, 39, 41, 44, 47, 53, 55, 62],
    videos: [19, 2, 3, 5, 11, 15, 21, 23, 26, 28],
  },
  'hyundai-service': {
    photos: [1, 3, 7, 9, 13, 14, 15, 17, 20, 22, 24],
    videos: [7, 2, 6, 8],
  },
  'hyundai-hesarghatta': {
    photos: [4, 1, 6, 8, 13, 22, 34, 37, 39, 49, 52, 58, 66, 69, 74, 79, 88, 108, 141, 148],
    videos: [23, 2, 8, 9, 21, 29, 33, 34, 36, 39],
  },
};
// Clips used in the home hero (higher resolution), as [project, video number].
export const HERO = [['pizza-koramangala', 1], ['hyundai-hesarghatta', 23], ['pizza-hsr', 26], ['hyundai-rajajinagar', 19], ['pizza-koramangala', 11], ['pizza-hsr', 21]];

const run = (args) => execFileSync(FFMPEG, ['-v', 'error', '-y', ...args], { stdio: ['ignore', 'ignore', 'pipe'] });
const manifest = {};
for (const [proj, pick] of Object.entries(PICKS)) {
  const dir = path.join(OUT, proj);
  fs.mkdirSync(dir, { recursive: true });
  manifest[proj] = { photos: [], videos: [] };

  for (const [i, n] of pick.photos.entries()) {
    const src = photoIndex[proj].find((p) => p.n === n).file;
    const name = `p${String(i + 1).padStart(2, '0')}`;
    const img = sharp(src, { failOn: 'none' }).rotate();
    const meta = await img.clone().metadata();
    const landscape = (meta.autoOrient?.width ?? meta.width) >= (meta.autoOrient?.height ?? meta.height);
    const targets = [['', 1920, 80], ['-md', 1200, 76], ['-sm', 720, 72]];
    for (const [suf, w, q] of targets) {
      const f = path.join(dir, `${name}${suf}.webp`);
      if (!fs.existsSync(f)) await img.clone().resize({ width: w, withoutEnlargement: true }).webp({ quality: q }).toFile(f);
    }
    const { width, height } = await sharp(path.join(dir, `${name}-sm.webp`)).metadata();
    manifest[proj].photos.push({ name, w: width, h: height, landscape });
  }

  for (const [i, n] of pick.videos.entries()) {
    const v = videoIndex[proj].find((x) => x.n === n);
    const name = `v${String(i + 1).padStart(2, '0')}`;
    const hero = HERO.some(([p, k]) => p === proj && k === n);
    const mp4 = path.join(dir, `${name}.mp4`);
    if (!fs.existsSync(mp4)) {
      run(['-i', v.file, '-an', '-vf', `scale='min(${hero ? 1920 : 1280},iw)':-2,fps=30`, '-c:v', 'libx264', '-preset', 'slow',
        '-crf', hero ? '25' : '27', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', mp4]);
    }
    const poster = path.join(dir, `${name}.webp`);
    if (!fs.existsSync(poster)) {
      const tmp = path.join(dir, `${name}.tmp.jpg`);
      run(['-ss', '0.3', '-i', mp4, '-frames:v', '1', tmp]);
      await sharp(tmp).webp({ quality: 74 }).toFile(poster);
      fs.unlinkSync(tmp);
    }
    const { width, height } = await sharp(poster).metadata();
    manifest[proj].videos.push({ name, dur: v.dur, w: width, h: height, hero });
  }
  console.log(proj, manifest[proj].photos.length, 'photos', manifest[proj].videos.length, 'videos');
}
const heroList = HERO.map(([p, n]) => ({ proj: p, name: manifest[p].videos[PICKS[p].videos.indexOf(n)].name }));
fs.mkdirSync('src/data', { recursive: true });
fs.writeFileSync('src/data/media.generated.js',
  `// AUTO-GENERATED by scripts/build-media.mjs — do not edit by hand.\nexport const MEDIA = ${JSON.stringify(manifest, null, 1)};\nexport const HERO_CLIPS = ${JSON.stringify(heroList)};\n`);
